package com.cocos.challenge.orders.application;

import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;

import com.cocos.challenge.orders.application.port.in.PlaceOrderCommand;
import com.cocos.challenge.orders.domain.OrderSizing;

/**
 * Deterministic fingerprint of an order request, used to detect an idempotency key reused for a different
 * intention. SHA-256 (lowercase hex) of a canonical, versioned text built from the command, not from the raw JSON:
 * <pre>v1|user=1|instrument=47|side=BUY|type=LIMIT|quantity=10|price=900.5
 * v1|user=1|instrument=-|side=CASH_IN|type=-|amount=5000|price=-</pre>
 * <ul>
 *     <li>numbers are normalized ({@code stripTrailingZeros().toPlainString()}): 900.50, 900.5 and 900.500 are the
 *     same intention;</li>
 *     <li>quantity and amount are distinguished ({@code quantity=10} vs {@code amount=10});</li>
 *     <li>nothing generated by the server is included (no timestamps, no MARKET execution price);</li>
 *     <li>the idempotency key itself is not part of the fingerprint.</li>
 * </ul>
 */
final class OrderRequestFingerprint {

    private static final String VERSION = "v1";

    private OrderRequestFingerprint() {
    }

    static String of(PlaceOrderCommand command) {
        return sha256(canonical(command));
    }

    static String canonical(PlaceOrderCommand command) {
        String sizing = switch (command.sizing()) {
            case OrderSizing.Quantity quantity -> "quantity=" + quantity.shares();
            case OrderSizing.Amount amount -> "amount=" + normalized(amount.value());
        };
        String price = command.limitPrice() == null ? "-" : normalized(command.limitPrice());
        return String.join("|", VERSION,
                "user=" + command.userId(),
                "instrument=" + (command.instrumentId() == null ? "-" : command.instrumentId()),
                "side=" + command.side().name(),
                "type=" + (command.type() == null ? "-" : command.type().name()),
                sizing,
                "price=" + price);
    }

    private static String normalized(BigDecimal value) {
        return value.stripTrailingZeros().toPlainString();
    }

    private static String sha256(String text) {
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256").digest(text.getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(digest);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 is required by every Java platform", e);
        }
    }
}
